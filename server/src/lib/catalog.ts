export function fallbackCategories() {
  return categories.map((category) => ({
    ...category,
    _count: { products: products.filter((product) => product.categoryId === category.id).length },
  }));
}

export function fallbackProducts(filters?: { category?: string; q?: string; featured?: boolean }) {
  return products.filter((product) => {
    if (filters?.featured && !product.featured) return false;
    if (filters?.category && filters.category !== "all" && product.category.slug !== filters.category) {
      return false;
    }
    if (filters?.q) {
      const q = filters.q.toLowerCase();
      return (
        product.name.toLowerCase().includes(q) ||
        product.description.toLowerCase().includes(q) ||
        product.category.name.toLowerCase().includes(q)
      );
    }
    return true;
  });
}

export function fallbackProduct(slug: string) {
  return products.find((product) => product.slug === slug) ?? null;
}

export function fallbackProductById(id: string) {
  return products.find((product) => product.id === id) ?? null;
}
